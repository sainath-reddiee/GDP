-- @pack Referential integrity
-- @description Every COMPANY spoke row resolves to its COMPANY_CORE hub row
-- @tags referential-integrity, orphan-keys

-- @query orphan_company_address
-- @severity ERROR
-- @description COMPANY_ADDRESS rows whose COMPANY_CORE_SKEY has no hub row in COMPANY_CORE
-- @tags orphan-keys
SELECT s.COMPANY_CORE_SKEY, COUNT(*) AS ORPHAN_ROWS
FROM DEV_GDP_SILVER_DB.COMPANY.COMPANY_ADDRESS s
LEFT JOIN DEV_GDP_SILVER_DB.COMPANY.COMPANY_CORE c ON c.COMPANY_CORE_SKEY = s.COMPANY_CORE_SKEY
WHERE s.COMPANY_CORE_SKEY IS NOT NULL AND c.COMPANY_CORE_SKEY IS NULL
GROUP BY s.COMPANY_CORE_SKEY

