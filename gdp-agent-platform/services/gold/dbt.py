"""Gold code generation (pure): an approved gold model and its mapping lines as dbt models, Iceberg DDL and a report.

Per gold table that is not a conformed dimension (those belong to their mastered domain's gold):
  ddl/gold/<domain>/<table>.sql          sequence + CREATE ICEBERG TABLE, per the gold-model skill's template
  models/gold/<domain>/<table>.sql       incremental merge on the business key; the existing skey kept (else the
                                         sequence), rows written only when new or their HKEY changed; mastered keys
                                         resolved through the full cross-reference (services/mdm/contract.py)
  models/gold/<domain>/_<domain>__gold.yml   columns, not_null and unique tests, relationships to the dimensions
                                         (ignoring -1, the unresolved key)
  release/gold-generation-report.json    inputs, conventions used, and every assumption to confirm in review
Nothing guesses a project macro: when the repository's conventions are known (`conventions`), they are used and
named in the report; otherwise plain SQL is generated and the report says what to replace.
"""

from __future__ import annotations

import json
from typing import Any, Dict, List, Optional

from services.gold.propose import AUDIT
from services.mdm import contract as mdm

ENGINE = "gdp-gold/engine-v1"


def _q(name: str) -> str:
    return name.lower()


def _hkey(columns: List[str]) -> str:
    parts = ", ".join(f"coalesce(to_varchar({_q(c)}), '')" for c in columns)
    return f"sha2(concat_ws('||', {parts}), 256)"


def ddl(entity: Dict[str, Any], env: str = "DEV") -> str:
    """The Iceberg DDL of one gold table (gold-model skill template)."""
    table, db, schema = entity["entity_name"], str(entity["database"]).replace("{ENV}", env.upper()), entity["schema"]
    pk = next(a["name"] for a in entity["attributes"] if a.get("is_pk"))
    width = max(len(a["name"]) for a in entity["attributes"]) + 2
    lines = []
    for a in entity["attributes"]:
        null = "" if a.get("nullable", True) and not a.get("is_pk") else "NOT NULL"
        default = " DEFAULT FALSE" if a["name"].startswith("IS_") and a["datatype"] == "BOOLEAN" else ""
        comment = (a.get("description") or a["name"].replace("_", " ").lower()).replace("'", "''")[:300]
        lines.append(f"    {a['name']:<{width}}{a['datatype']:<16}{default}{(' ' + null) if null else ''}  COMMENT '{comment}'")
    cons = [f"    CONSTRAINT PK_{table} PRIMARY KEY ({pk})"]
    uk = [k for k in entity.get("business_keys") or [] if k != pk]
    if uk:
        cons.append(f"    CONSTRAINT UK_{table} UNIQUE ({', '.join(uk)})")
    for fk in entity.get("_fks") or []:
        cons.append(f"    CONSTRAINT FK_{table}_{fk['column']} FOREIGN KEY ({fk['column']}) REFERENCES {fk['to']} ({fk['to_column']})")
    loc = f"gdp-sf-{env.lower()}-gold/{schema.lower()}/{table.lower()}"
    return (f"-- generated by {ENGINE}: review before running\n"
            f"CREATE SEQUENCE IF NOT EXISTS {db}.{schema}.SEQ_{table}_SKEY START WITH 1 INCREMENT BY 1 NOORDER;\n\n"
            f"CREATE ICEBERG TABLE IF NOT EXISTS {db}.{schema}.{table} (\n" + ",\n".join(lines + cons) + "\n)\n"
            f"EXTERNAL_VOLUME = 'GDP_SF_{env.upper()}_GOLD'\nCATALOG = 'SNOWFLAKE'\nBASE_LOCATION = '{loc}'\n"
            f"COMMENT = '{(entity.get('description') or table).replace(chr(39), chr(39) * 2)[:300]}';\n")


def _source_ref(table_fqn: str, conventions: Dict[str, Any]) -> str:
    """ref() of a silver model: the table name, lower-case (the gdp-dbt naming of silver hubs)."""
    name = table_fqn.split(".")[-1].lower()
    return (conventions.get("refs") or {}).get(table_fqn.upper(), f"{{{{ ref('{name}') }}}}")


def model_sql(entity: Dict[str, Any], lines: List[Dict[str, Any]], spec: Dict[str, Any], *,
              mastered: Dict[str, Dict[str, Any]], consumes: List[Dict[str, Any]], conventions: Dict[str, Any],
              assumptions: List[str]) -> str:
    """The dbt model of one fact, bridge or proposed dimension."""
    table = entity["entity_name"]
    skey = next(a["name"] for a in entity["attributes"] if a.get("is_pk"))
    mine = [l for l in lines if l["gold_table"] == table]
    sources = sorted({l["source_table"] for l in mine if l.get("source_table") and l["kind"] in ("COLUMN", "RESOLVE")})
    if not sources:
        raise ValueError(f"{table} has no source table in its mapping lines")
    driving = sources[0]
    keys = [k for k in entity.get("business_keys") or [] if k != skey] or [skey]
    business = [a["name"] for a in entity["attributes"]
                if not a.get("is_pk") and a["name"] != f"{table}_HKEY" and a["name"] not in {n for n, _ in AUDIT}]
    ctes, joins, select = [], [], []
    # a reviewer's transformation (STTM) is computed on the silver row itself, before any dimension is joined
    tx = [(l["gold_column"], l["sql"]) for l in mine if l["kind"] == "COLUMN" and l.get("sql")]
    extra = "".join(f",\n           {sql} as {_q('tx_' + col)}" for col, sql in tx)
    # every silver row, active or not, so a deactivation in silver reaches gold
    ctes.append(f"src as (\n    select *{extra}\n    from {_source_ref(driving, conventions)}\n)")
    consumed = {str(c["domain"]).upper(): c for c in consumes}
    resolved_domains = set()
    # the approved table's columns drive the SELECT (a reviewer may have changed the model after the proposal)
    line_of = {l["gold_column"]: l for l in mine}
    ordered = []
    for a in entity["attributes"]:
        if a.get("is_pk") or a["name"] == f"{table}_HKEY" or a["name"] in {n for n, _ in AUDIT}:
            continue
        if a["name"] in line_of:
            ordered.append(line_of[a["name"]])
        else:
            assumptions.append(f"{table}.{a['name']}: added in review without a mapping line; generated as NULL, map it")
            ordered.append({"gold_table": table, "gold_column": a["name"], "kind": "NULL", "datatype": a["datatype"]})
    for l in ordered:
        col = l["gold_column"]
        if l["kind"] == "NULL":
            select.append(f"null::{l['datatype'].replace('LONG', 'NUMBER(38,0)')} as {_q(col)}")
            continue
        if l["kind"] == "COLUMN" and l.get("sql"):
            select.append(f"src.{_q('tx_' + col)} as {_q(col)}")
            continue
        if l["kind"] == "COLUMN":
            expr = _q(l["source_column"])
            target = next((a for a in entity["attributes"] if a["name"] == col), None)
            if target and target["datatype"] not in ("STRING",) and (l.get("expression") or "").startswith("cast"):
                expr = f"try_cast(to_varchar(src.{_q(l['source_column'])}) as {target['datatype'].replace('LONG', 'NUMBER(38,0)')})" \
                    if target["datatype"] not in ("BOOLEAN", "DATE", "TIMESTAMP_NTZ", "TIMESTAMP_TZ") else f"src.{_q(l['source_column'])}::{target['datatype']}"
            else:
                expr = f"src.{expr}"
            select.append(f"{expr} as {_q(col)}")
        elif l["kind"] == "RESOLVE" and l.get("source_layer") == "MDM":
            dom = next((d for d, c in mastered.items() if c["gold"]["dimension"] in (l.get("expression") or "")), None)
            if not dom:
                assumptions.append(f"{table}.{col}: no mastered contract matched its resolution; set to -1")
                select.append(f"-1 as {_q(col)}")
                continue
            c = mastered[dom]
            prefix = col[: -len(c["gold"]["skey"])] if col.endswith(c["gold"]["skey"]) else ""
            alias = f"{prefix.lower()}{c['gold']['dimension'].lower()}"
            r = mdm.dbt_resolution(c, input_alias="src", input_skey=l["source_column"], out_column=c["gold"]["skey"])
            if dom not in resolved_domains:
                ctes.append(r["ctes"])
                resolved_domains.add(dom)
            name = c["gold"]["dimension"].lower()
            joins.append(f"left join {name}_resolution {alias}_r on src.{_q(l['source_column'])} = {alias}_r.{c['pre_mdm']['skey'].lower()}")
            select.append(f"nvl({alias}_r.{c['gold']['skey'].lower()}, -1) as {_q(col)}")
        elif l["kind"] == "RESOLVE" and col == "DIM_DATA_SOURCE_SKEY":
            ds = conventions.get("data_source") or {}
            relation = ds.get("relation") or "{{ ref('dim_data_source') }}"
            if not ds:
                assumptions.append("DIM_DATA_SOURCE_SKEY: assumed ref('dim_data_source') with DIM_DATA_SOURCE_SKEY and DATA_SOURCE_NAME, "
                                   "joined on the source system name; confirm against the existing gold facts before merging")
            ctes.append(f"""data_source as (
    select r.{_q('GDP_SOURCE_SYSTEM_SKEY')}, d.{_q(ds.get('skey') or 'DIM_DATA_SOURCE_SKEY')} as dim_data_source_skey
    from {{{{ source('silver_shared', 'ref_gdp_source_system') }}}} r
    join {relation} d on upper(d.{_q(ds.get('name') or 'DATA_SOURCE_NAME')}) = upper(r.gdp_source_system_name)
)""")
            joins.append("left join data_source ds on src.ref_gdp_source_system_skey = ds.gdp_source_system_skey")
            select.append("nvl(ds.dim_data_source_skey, -1) as dim_data_source_skey")
        elif l["kind"] == "RESOLVE":   # a proposed dimension key, or a parent fact key
            dim = next((r["to_entity"] for r in spec.get("relationships") or [] if r["from_entity"] == table and r["from_column"] == col), None)
            if dim and dim.startswith("DIM_"):
                value_col = l["source_column"]
                joins.append(f"left join {{{{ ref('{dim.lower()}') }}}} {dim.lower()} on {dim.lower()}.{_q(value_col)} = src.{_q(value_col)}")
                select.append(f"nvl({dim.lower()}.{_q(dim + '_SKEY')}, -1) as {_q(col)}")
            elif dim:
                # the parent fact keeps no silver skey: go through the parent silver hub to its merge key
                # (SOURCE_UNIQUE_ID + data source), which the parent fact is unique on
                parent_skey = l["source_column"]
                parent_hub = parent_skey[: -len("_SKEY")]
                if any(c.startswith("data_source as (") for c in ctes):
                    ctes.append(f"""parent_{_q(dim)} as (
    select p.{_q(parent_skey)}, f.{_q(col)}
    from {{{{ ref('{parent_hub.lower()}') }}}} p
    join data_source pds on p.ref_gdp_source_system_skey = pds.gdp_source_system_skey
    join {{{{ ref('{dim.lower()}') }}}} f on f.source_unique_id = p.source_unique_id and f.dim_data_source_skey = pds.dim_data_source_skey
)""")
                    joins.append(f"left join parent_{_q(dim)} on src.{_q(parent_skey)} = parent_{_q(dim)}.{_q(parent_skey)}")
                    select.append(f"nvl(parent_{_q(dim)}.{_q(col)}, -1) as {_q(col)}")
                else:
                    assumptions.append(f"{table}.{col}: {table} has no REF_GDP_SOURCE_SYSTEM_SKEY, so the parent {dim} cannot be "
                                       "matched on its merge key; set to -1, map it in review")
                    select.append(f"-1 /* see the generation report */ as {_q(col)}")
            else:
                select.append(f"-1 as {_q(col)}")
    hk = _hkey(business)
    uk = ", ".join(f"'{_q(k)}'" for k in keys)
    hist = conventions.get("history_hook")
    config = [f"materialized='incremental'", "incremental_strategy='merge'", f"unique_key=[{uk}]",
              f"merge_exclude_columns=['{_q(skey)}', 'gdp_inserted_ts', 'gdp_inserted_by']",
              f"tags=['gold', 'gold_{spec['domain'].lower()}']", "full_refresh=false"]
    if hist:
        config.append(f"post_hook=[\"{hist}\"]")
    else:
        assumptions.append(f"{table}: no history hook (the repository's m_insert_history_gold call was not found in the code index); add it in review")
    body = ",\n        ".join(select)
    with_ctes = ",\n".join(ctes)
    join_text = "\n    ".join(joins)
    keys_join = " and ".join(f"t.{_q(k)} = s.{_q(k)}" for k in keys)
    return f"""-- generated by {ENGINE} from the approved gold model; review before merging
{{{{ config({', '.join(config)}) }}}}

with {with_ctes},
shaped as (
    select
        {body},
        src.gdp_is_active as gdp_is_active
    from src
    {join_text}
),
hashed as (
    select *, {hk} as {_q(table)}_hkey from shaped
)
select
    {{% if is_incremental() %}} coalesce(t.{_q(skey)}, {{{{ this.database }}}}.{{{{ this.schema }}}}.seq_{_q(table)}_skey.nextval)
    {{% else %}} {{{{ this.database }}}}.{{{{ this.schema }}}}.seq_{_q(table)}_skey.nextval {{% endif %}} as {_q(skey)},
    s.* exclude (gdp_is_active, {_q(table)}_hkey),
    s.{_q(table)}_hkey,
    s.gdp_is_active,
    current_timestamp()::timestamp_ntz as gdp_inserted_ts,
    current_user() as gdp_inserted_by,
    current_timestamp()::timestamp_ntz as gdp_updated_ts,
    current_user() as gdp_updated_by
from hashed s
{{% if is_incremental() %}}
left join {{{{ this }}}} t on {keys_join}
where t.{_q(skey)} is null or t.{_q(table)}_hkey <> s.{_q(table)}_hkey or t.gdp_is_active <> s.gdp_is_active
{{% endif %}}
"""


def dimension_sql(entity: Dict[str, Any], lines: List[Dict[str, Any]], spec: Dict[str, Any], conventions: Dict[str, Any]) -> str:
    """A proposed descriptor dimension: one row per distinct value of its column in silver."""
    table = entity["entity_name"]
    skey = f"{table}_SKEY"
    col = entity["business_keys"][0]
    src = next(l for l in lines if l["gold_table"] == table and l["kind"] == "COLUMN")
    seq = f"{{{{ this.database }}}}.{{{{ this.schema }}}}.seq_{_q(table)}_skey"
    return f"""-- generated by {ENGINE}: a proposed dimension, one row per {col} value
{{{{ config(materialized='incremental', incremental_strategy='merge', unique_key=['{_q(col)}'],
          merge_exclude_columns=['{_q(skey)}', 'gdp_inserted_ts', 'gdp_inserted_by'], tags=['gold', 'gold_{spec['domain'].lower()}'], full_refresh=false) }}}}

with vals as (
    select distinct {_q(src['source_column'])} as {_q(col)}
    from {_source_ref(src['source_table'], conventions)}
    where {_q(src['source_column'])} is not null
)
select
    {{% if is_incremental() %}} coalesce(t.{_q(skey)}, {seq}.nextval) {{% else %}} {seq}.nextval {{% endif %}} as {_q(skey)},
    v.{_q(col)},
    {_hkey([col])} as {_q(table)}_hkey,
    true as gdp_is_active,
    current_timestamp()::timestamp_ntz as gdp_inserted_ts,
    current_user() as gdp_inserted_by,
    current_timestamp()::timestamp_ntz as gdp_updated_ts,
    current_user() as gdp_updated_by
from vals v
{{% if is_incremental() %}}
left join {{{{ this }}}} t on t.{_q(col)} = v.{_q(col)}
where t.{_q(skey)} is null
{{% endif %}}
"""


def schema_yml(domain: str, entities: List[Dict[str, Any]], spec: Dict[str, Any]) -> str:
    out = ["version: 2", "", "models:"]
    for e in entities:
        skey = next(a["name"] for a in e["attributes"] if a.get("is_pk"))
        out += [f"  - name: {_q(e['entity_name'])}", f"    description: \"{(e.get('description') or '').replace(chr(34), chr(39))}\"", "    columns:"]
        for a in e["attributes"]:
            out.append(f"      - name: {_q(a['name'])}")
            if a.get("description"):
                out.append(f"        description: \"{a['description'].replace(chr(34), chr(39))[:300]}\"")
            tests = []
            if a["name"] == skey:
                tests += ["unique", "not_null"]
            elif not a.get("nullable", True):
                tests.append("not_null")
            rel = next((r for r in spec.get("relationships") or [] if r["from_entity"] == e["entity_name"] and r["from_column"] == a["name"]), None)
            if rel:
                tests.append({"relationships": {"to": f"ref('{_q(rel['to_entity'])}')", "field": _q(rel["to_column"]),
                                                "config": {"where": f"{_q(a['name'])} <> -1"}}})
            if tests:
                out.append("        tests:")
                for t in tests:
                    if isinstance(t, str):
                        out.append(f"          - {t}")
                    else:
                        r = t["relationships"]
                        out += ["          - relationships:", f"              to: {r['to']}", f"              field: {r['field']}",
                                "              config:", f"                where: \"{r['config']['where']}\""]
    return "\n".join(out) + "\n"


def generate(spec: Dict[str, Any], lines: List[Dict[str, Any]], *, mastered: Dict[str, Dict[str, Any]],
             consumes: List[Dict[str, Any]], conventions: Optional[Dict[str, Any]] = None, env: str = "DEV",
             build: Optional[Dict[str, Any]] = None, only: Optional[List[str]] = None) -> Dict[str, Any]:
    """{files: {path: text}, report, lineage: [edges]} for the gold tables of an approved gold model (or only the
    named ones: a Gold run builds its target table and the proposed dimensions it references)."""
    conventions = conventions or {}
    domain = spec["domain"].lower()
    own = [e for e in spec["design"]["entities"] if not e.get("conformed_from") and e.get("status", "ACTIVE") != "RETIRED"
           and (only is None or e["entity_name"] in only)]
    by_name = {e["entity_name"]: e for e in spec["design"]["entities"]}
    files: Dict[str, str] = {}
    assumptions: List[str] = []
    for e in own:
        e = dict(e, _fks=[{"column": r["from_column"], "to": f"{by_name[r['to_entity']].get('database') or spec['physical_defaults']['database']}."
                                                          f"{by_name[r['to_entity']].get('schema') or spec['physical_defaults']['schema']}.{r['to_entity']}",
                           "to_column": r["to_column"]}
                          for r in spec.get("relationships") or [] if r["from_entity"] == e["entity_name"] and r["to_entity"] in by_name])
        files[f"ddl/gold/{domain}/{e['entity_name'].lower()}.sql"] = ddl(e, env)
        if e["table_type"] == "DIMENSION":
            files[f"models/gold/{domain}/{e['entity_name'].lower()}.sql"] = dimension_sql(e, lines, spec, conventions)
        else:
            files[f"models/gold/{domain}/{e['entity_name'].lower()}.sql"] = model_sql(
                e, lines, spec, mastered=mastered, consumes=consumes, conventions=conventions, assumptions=assumptions)
    files[f"models/gold/{domain}/_{domain}__gold.yml"] = schema_yml(domain, own, spec)
    assumptions.append(f"models/gold/{domain} must build into {spec['physical_defaults']['database']}.{spec['physical_defaults']['schema']} "
                       "(per environment): map the folder's +database and +schema in dbt_project.yml as the existing gold folders do")
    assumptions.append("run the ddl/gold files first (sequences and Iceberg tables); the models merge into the existing tables")
    gold_obj = lambda t: f"{spec['physical_defaults']['database']}.{spec['physical_defaults']['schema']}.{t}"   # noqa: E731
    lineage = [{"from_layer": "SILVER_PRE_MDM" if l.get("source_layer") == "MDM" else (l.get("source_layer") or "SILVER_PRE_MDM"),
                "from_object": l["source_table"], "from_column": l.get("source_column"),
                "to_layer": "GOLD", "to_object": gold_obj(l["gold_table"]),
                "to_column": l["gold_column"], "kind": "RESOLVE" if l["kind"] == "RESOLVE" else "BUILD", "expression": l.get("expression")}
               for l in lines if l.get("source_table") and any(e["entity_name"] == l["gold_table"] for e in own)]
    # a resolved key also comes from the dimension it points at (a conformed or proposed dimension)
    for r in spec.get("relationships") or []:
        if any(e["entity_name"] == r["from_entity"] for e in own) and r["to_entity"] in by_name:
            to = by_name[r["to_entity"]]
            lineage.append({"from_layer": "GOLD", "from_object": f"{to.get('database') or spec['physical_defaults']['database']}."
                                                                 f"{to.get('schema') or spec['physical_defaults']['schema']}.{r['to_entity']}",
                            "from_column": r["to_column"], "to_layer": "GOLD", "to_object": gold_obj(r["from_entity"]),
                            "to_column": r["from_column"], "kind": "RESOLVE", "expression": f"{r['from_entity']}.{r['from_column']} references {r['to_entity']}"})
    report = {"engine": ENGINE, "domain": spec["domain"], "build": build, "tables": [e["entity_name"] for e in own],
              "conformed": [e["entity_name"] for e in spec["design"]["entities"] if e.get("conformed_from")],
              "conventions": {k: v for k, v in conventions.items() if k != "refs"} or "none found in the code index: plain SQL",
              "assumptions": sorted(set(assumptions)), "files": sorted(files)}
    files["release/gold-generation-report.json"] = json.dumps(report, indent=2)
    return {"files": files, "report": report, "lineage": lineage}
