"""Files rendered from a v2 domain model (pure): DDL, domain_pack.json, dbt schema tests and a CSV data dictionary.

Retired entities and columns are left out. Snowflake enforces only NOT NULL; PRIMARY KEY, UNIQUE and FOREIGN KEY are
informational (RELY lets the optimizer use them), and CHECK constraints do not exist, so checks are written as dbt
singular tests next to the not_null, unique, accepted_values and relationships tests.
"""

from __future__ import annotations

import csv
import io
import json
import re
from typing import Any, Dict, List, Optional

from services.catalog.models import iceberg_type
from services.modeling import spec_v2


def _q(text: Any) -> str:
    return str(text or "").replace("'", "''")


def _type(spec: Dict[str, Any], datatype: str) -> str:
    return iceberg_type(datatype) if spec["physical_defaults"]["platform"] == "ICEBERG" else (datatype or "VARCHAR").upper()


def _fqn(spec: Dict[str, Any], entity: Dict[str, Any]) -> str:
    db, schema = spec_v2.placement(spec, entity)
    return ".".join(p for p in (db, schema, entity["entity_name"]) if p)


def render_ddl(spec: Dict[str, Any]) -> str:
    spec = spec_v2.active(spec)
    platform = spec["physical_defaults"]["platform"]
    by_name = {e["entity_name"]: e for e in spec["design"]["entities"]}
    out = [f"-- {spec['domain']} domain model, target {platform}. Generated by the Model Workbench; review before running.",
           "-- Snowflake enforces NOT NULL only; keys are informational and checks are tested in dbt."]
    for e in spec["design"]["entities"]:
        lines = []
        for a in e["attributes"]:
            col = f"    {a['name']} {_type(spec, a['datatype'])}"
            if a.get("default"):
                col += f" DEFAULT {a['default']}"
            if not a.get("nullable", True):
                col += " NOT NULL"
            note = a.get("description") or a.get("business_definition")
            if note:
                col += f" COMMENT '{_q(note)[:1000]}'"
            lines.append(col)
        pk = [a["name"] for a in e["attributes"] if a.get("is_pk")]
        if pk:
            lines.append(f"    CONSTRAINT PK_{e['entity_name']} PRIMARY KEY ({', '.join(pk)})")
        uniques = [u for u in e.get("unique_constraints") or [] if u]
        uniques += [[a["name"]] for a in e["attributes"] if a.get("is_unique") and [a["name"]] not in uniques and [a["name"]] != pk]
        for i, u in enumerate(uniques, start=1):
            lines.append(f"    CONSTRAINT UQ_{e['entity_name']}_{i} UNIQUE ({', '.join(u)})")
        for r in spec.get("relationships") or []:
            if r["from_entity"] == e["entity_name"] and r["to_entity"] in by_name:
                rely = " RELY" if r.get("enforce") == "RELY" else ""
                lines.append(f"    CONSTRAINT {r['name']} FOREIGN KEY ({r['from_column']}) "
                             f"REFERENCES {_fqn(spec, by_name[r['to_entity']])} ({r['to_column']}){rely}")
        body = ",\n".join(lines)
        phys = e.get("physical") or {}
        opts = []
        if phys.get("cluster_by"):
            opts.append(f"  CLUSTER BY ({', '.join(phys['cluster_by'])})")
        if phys.get("retention_days") is not None and platform != "ICEBERG":
            opts.append(f"  DATA_RETENTION_TIME_IN_DAYS = {int(phys['retention_days'])}")
        comment = f"  COMMENT = '{_q(e.get('description') or e['entity_name'])[:1000]}'"
        checks = "".join(f"\n-- CHECK {c['name']}: {c['expression']} (tested by dbt)" for c in e.get("checks") or [])
        if platform == "ICEBERG":
            ice = spec["physical_defaults"]["iceberg"]
            location = ice.get("base_location") or f"{spec_v2.placement(spec, e)[1]}/{e['entity_name']}".lower()
            out.append(f"CREATE ICEBERG TABLE IF NOT EXISTS {_fqn(spec, e)} (\n{body}\n)\n"
                       f"  CATALOG = '{_q(ice.get('catalog') or 'SNOWFLAKE')}'\n"
                       f"  EXTERNAL_VOLUME = '{_q(ice.get('external_volume') or '<external_volume>')}'\n"
                       f"  BASE_LOCATION = '{_q(location)}'\n" + ("\n".join(opts) + "\n" if opts else "") + comment + ";"
                       + checks)
        else:
            kind = "TRANSIENT TABLE" if phys.get("transient") else "TABLE"
            out.append(f"CREATE {kind} IF NOT EXISTS {_fqn(spec, e)} (\n{body}\n)\n"
                       + ("\n".join(opts) + "\n" if opts else "") + comment + ";" + checks)
    return "\n\n".join(out) + "\n"


def render_pack(spec: Dict[str, Any], base_pack: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """domain_pack.json: the domain metadata and knowledge of `base_pack` (when given) with every target replaced by
    the model's active entities."""
    pack = json.loads(json.dumps(base_pack)) if base_pack else {"domain": {}, "targets": [], "knowledge": []}
    meta = pack.setdefault("domain", {})
    meta["name"] = spec["domain"]
    if spec.get("description"):
        meta["description"] = spec["description"]
    meta.setdefault("description", f"{spec['domain']} domain")
    phys = spec["physical_defaults"]
    if phys.get("database"):
        meta["silver_database"] = phys["database"]
    if phys.get("schema"):
        meta["silver_schema"] = phys["schema"]
    pack["targets"] = spec_v2.pack_targets(spec)
    pack.setdefault("knowledge", [])
    return pack


def _snake(name: str) -> str:
    return re.sub(r"[^a-z0-9_]+", "_", str(name or "").lower()).strip("_") or "model"


def render_dbt_tests(spec: Dict[str, Any], project_dir: str = "") -> Dict[str, str]:
    """models/marts/<domain>/_schema.yml (descriptions, PII meta, not_null, unique, accepted_values and relationships
    tests) and one singular test per check."""
    spec = spec_v2.active(spec)
    root = (project_dir.strip("/") + "/") if project_dir.strip("/") else ""
    domain = _snake(spec["domain"])
    lines = ["version: 2", "", "models:"]
    files: Dict[str, str] = {}
    for e in spec["design"]["entities"]:
        model = _snake(e["entity_name"])
        pk = [a["name"] for a in e["attributes"] if a.get("is_pk")]
        lines += [f"  - name: {model}", f"    description: {json.dumps((e.get('description') or '')[:500])}", "    columns:"]
        for a in e["attributes"]:
            tests: List[str] = []
            if a["name"] in pk or not a.get("nullable", True):
                tests.append("          - not_null")
            if (a["name"] in pk and len(pk) == 1) or a.get("is_unique"):
                tests.append("          - unique")
            if a.get("accepted_values"):
                tests += ["          - accepted_values:", f"              values: {json.dumps(a['accepted_values'][:200])}"]
            for r in spec.get("relationships") or []:
                if r["from_entity"] == e["entity_name"] and r["from_column"] == a["name"]:
                    tests += ["          - relationships:", f"              to: ref('{_snake(r['to_entity'])}')",
                              f"              field: {r['to_column'].lower()}"]
            lines.append(f"      - name: {a['name'].lower()}")
            note = a.get("description") or a.get("business_definition")
            if note:
                lines.append(f"        description: {json.dumps(note[:500])}")
            if (a.get("pii") or {}).get("flag"):
                lines += ["        meta:", "          pii: true"]
                if a["pii"].get("classification"):
                    lines.append(f"          pii_classification: {a['pii']['classification'].lower()}")
            if tests:
                lines.append("        tests:")
                lines += tests
        for c in e.get("checks") or []:
            files[f"{root}tests/{domain}/{model}__{_snake(c['name'])}.sql"] = (
                f"-- {c['name']}: rows of {e['entity_name']} that break the check\n"
                f"select *\nfrom {{{{ ref('{model}') }}}}\nwhere not ({c['expression']})\n")
    files[f"{root}models/marts/{domain}/_schema.yml"] = "\n".join(lines) + "\n"
    return files


def render_dbt(spec: Dict[str, Any], project_dir: str = "") -> Dict[str, str]:
    """Sources, staging and mart models (the Modeling hub renderer on the active model) with the v2 tests."""
    from services.catalog.models import render_dbt as v1_dbt

    files = v1_dbt(spec_v2.active(spec), project_dir)
    files.update(render_dbt_tests(spec, project_dir))
    return files


def data_dictionary(spec: Dict[str, Any]) -> str:
    """One row per column (retired ones included and marked), for reviewers and business users."""
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["subject_area", "entity", "table_type", "entity_status", "column", "datatype", "nullable", "primary_key",
                     "business_key", "unique", "default", "pii", "pii_classification", "semantic_type", "accepted_values",
                     "description", "business_definition", "column_status"])
    for e in spec["design"]["entities"]:
        for a in e["attributes"]:
            pii = a.get("pii") or {}
            writer.writerow([e.get("subject_area") or "", e["entity_name"], e["table_type"], e.get("status"), a["name"],
                             a["datatype"], a.get("nullable"), a.get("is_pk"), a["name"] in (e.get("business_keys") or []),
                             a.get("is_unique"), a.get("default") or "", pii.get("flag"), pii.get("classification") or "",
                             a.get("semantic_type") or "", "|".join(a.get("accepted_values") or []),
                             a.get("description") or "", a.get("business_definition") or "", a.get("status")])
    return buf.getvalue()
