-- Airflow failure-resolution lab: the credential the lab DAGs sign in with. Nothing is created here.
-- The DAGs use an existing Snowflake user that holds the account role DATA_ENGINEER: at a client, the service account
-- Airflow already runs as; for a local test, your own user. The lab tables (CORE.LAB_*) are granted to the platform's
-- DATA_ENGINEER database role when setup_lab.sql, reset.sql or a fix creates them.
--
-- Key pair, in WSL:
--      openssl genrsa 2048 | openssl pkcs8 -topk8 -nocrypt -out ~/airflow/lab_key.p8 && chmod 600 ~/airflow/lab_key.p8
--      openssl rsa -in ~/airflow/lab_key.p8 -pubout | grep -v -- '-----' | tr -d '\n'
-- then, signed in as that user (a user may set its own key; slot 2 leaves an existing key alone):
--      ALTER USER <user> SET RSA_PUBLIC_KEY_2 = '<the single line printed above>';
-- When the lab is done:
--      ALTER USER <user> UNSET RSA_PUBLIC_KEY_2;     and delete ~/airflow/lab_key.p8
