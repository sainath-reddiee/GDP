-- V037 QA Store and Data Quality Store.
-- Applied once; never edit after it has been applied. Add a new V### instead.
--
-- QA Store (domain test packages; privileges PACKAGE.EDIT and PACKAGE.APPROVE): deterministic SQL assertions owned
-- by a domain (reconciliations, orphan keys, duplicate business keys, joins that must resolve). A pack is versioned:
-- every save is a new DRAFT version, a version is submitted and approved (four eyes by default policy), and the
-- approved version is the one that runs and feeds QA_TEST knowledge (and so Cortex Search and the QA prompts).
--   GOVERNANCE.DOMAIN_QA_PACKS    one row per pack version (header)
--   GOVERNANCE.DOMAIN_QA_QUERIES  the queries of each pack version
-- Executions are stored in QUALITY.QA_RUN / QA_RESULT with SCOPE 'DOMAIN' (RUN_ID NULL since V028).
--
-- Data Quality Store: declarative Soda / Great Expectations checks per table and column, managed without a run.
--   GOVERNANCE.DQ_CHECKS_CATALOG  CHECK_DEFINITION (the platform's neutral form) is authoritative and is what the
--                                 scanner runs; SODA_DSL is rendered from it for display and export.
--   GOVERNANCE.DQ_SCHEDULE        one Snowflake task per scheduled table (QUALITY.RUN_TABLE_SCAN)
-- QUALITY.CHECK_RUN / CHECK_RESULT accept table scans: RUN_ID becomes nullable (as V028 did for QA) and SCOPE,
-- TABLE_FQN and CATALOG_CHECK_ID are added. Every statement is safe to run again (IF NOT EXISTS).

CREATE TABLE IF NOT EXISTS {{database}}.GOVERNANCE.DOMAIN_QA_PACKS (
    PACK_ID        VARCHAR(36)    NOT NULL,
    VERSION        NUMBER(6,0)    NOT NULL,
    DOMAIN_ID      VARCHAR(36)    NOT NULL,
    NAME           VARCHAR(128)   NOT NULL,
    DESCRIPTION    VARCHAR(4000),
    TAGS           ARRAY,
    STATUS         VARCHAR(20)    NOT NULL,   -- DRAFT | PENDING_APPROVAL | APPROVED | SUPERSEDED | RETIRED
    SOURCE         VARCHAR(8)     NOT NULL,   -- UI | REPO (domain/<name>/qa/<pack>.sql)
    CHANGE_NOTE    VARCHAR(2000),
    CREATED_BY     VARCHAR(256)   DEFAULT CURRENT_USER(),
    CREATED_AT     TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    SUBMITTED_BY   VARCHAR(256),
    SUBMITTED_AT   TIMESTAMP_LTZ,
    APPROVED_BY    VARCHAR(256),
    APPROVED_AT    TIMESTAMP_LTZ,
    CONSTRAINT PK_DOMAIN_QA_PACKS PRIMARY KEY (PACK_ID, VERSION)
);

CREATE TABLE IF NOT EXISTS {{database}}.GOVERNANCE.DOMAIN_QA_QUERIES (
    QUERY_ID        VARCHAR(64)    NOT NULL,   -- stable across versions: <pack>:<query name>
    PACK_ID         VARCHAR(36)    NOT NULL,
    PACK_VERSION    NUMBER(6,0)    NOT NULL,
    QUERY_NAME      VARCHAR(128)   NOT NULL,
    DESCRIPTION     VARCHAR(4000),
    SQL_EXPRESSION  VARCHAR(16000) NOT NULL,
    SEVERITY        VARCHAR(16)    DEFAULT 'ERROR',   -- ERROR | WARN | INFO
    EXPECTATION     VARCHAR(1000)  DEFAULT '0 rows',  -- how a result passes (services/qa/run.evaluate)
    TAGS            ARRAY,
    ORDINAL         NUMBER(6,0),
    CREATED_BY      VARCHAR(256)   DEFAULT CURRENT_USER(),
    UPDATED_AT      TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DOMAIN_QA_QUERIES PRIMARY KEY (QUERY_ID, PACK_VERSION)
);

CREATE TABLE IF NOT EXISTS {{database}}.GOVERNANCE.DQ_CHECKS_CATALOG (
    CHECK_ID          VARCHAR(64)    NOT NULL,
    TABLE_NAME        VARCHAR(800)   NOT NULL,   -- DATABASE.SCHEMA.TABLE
    COLUMN_NAME       VARCHAR(256),              -- NULL for table-level checks
    CHECK_TYPE        VARCHAR(64)    NOT NULL,   -- NOT_NULL | UNIQUE | FRESHNESS | ROW_COUNT | ACCEPTED_VALUES | ...
    CHECK_DEFINITION  VARIANT        NOT NULL,   -- neutral form {kind, ...}; what the scanner runs
    SODA_DSL          VARCHAR(4000)  NOT NULL,   -- rendered SodaCL, e.g. missing_count(EMAIL) = 0
    SEVERITY          VARCHAR(16)    DEFAULT 'WARN',   -- WARN | FAIL
    STATUS            VARCHAR(16)    DEFAULT 'ACTIVE', -- ACTIVE | PAUSED | RETIRED
    ORIGIN            VARCHAR(16)    NOT NULL,   -- PROFILE | RUN | USER
    DOMAIN_ID         VARCHAR(36),
    SCHEDULE_CRON     VARCHAR(64),
    LAST_RUN_STATUS   VARCHAR(16),               -- PASS | WARN | FAIL | ERROR | NOT_EVALUATED
    LAST_RUN_AT       TIMESTAMP_NTZ,
    LAST_MEASURED     FLOAT,
    CREATED_BY        VARCHAR(256)   DEFAULT CURRENT_USER(),
    CREATED_AT        TIMESTAMP_NTZ  DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT        TIMESTAMP_NTZ,
    CONSTRAINT PK_DQ_CHECKS_CATALOG PRIMARY KEY (CHECK_ID)
);

CREATE TABLE IF NOT EXISTS {{database}}.GOVERNANCE.DQ_SCHEDULE (
    TABLE_NAME   VARCHAR(800)   NOT NULL,
    CRON         VARCHAR(64)    NOT NULL,
    TASK_NAME    VARCHAR(256)   NOT NULL,
    ENABLED      BOOLEAN        DEFAULT TRUE,
    CREATED_BY   VARCHAR(256)   DEFAULT CURRENT_USER(),
    UPDATED_AT   TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DQ_SCHEDULE PRIMARY KEY (TABLE_NAME)
);

