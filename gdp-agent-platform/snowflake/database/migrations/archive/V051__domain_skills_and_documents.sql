-- V051 Domain skills and domain documents.
-- KNOWLEDGE.DOMAIN_SKILL: skills attached to a domain for a stage. Runs of that domain load them at that stage in
--   addition to the stage's bound skills (MODE ADD), or in place of one of them (MODE REPLACE, REPLACES = its name).
-- CONFLUENCE.SOURCE / CONFLUENCE.PAGE: Confluence pages or spaces linked to a domain, and uploaded documents, with
--   the text and version last read; their knowledge is proposed for a steward's review (ORIGIN CONFLUENCE, DOCUMENT).
-- Applied once; never edit after it has been applied. Add a new V### instead. Safe to run again.

CREATE TABLE IF NOT EXISTS {{database}}.KNOWLEDGE.DOMAIN_SKILL (
    DOMAIN_ID    VARCHAR(36)   NOT NULL,
    STAGE        VARCHAR(32)   NOT NULL,
    SKILL_NAME   VARCHAR(128)  NOT NULL,
    MODE         VARCHAR(8)    DEFAULT 'ADD',      -- ADD | REPLACE
    REPLACES     VARCHAR(128),                     -- the stage skill it stands in for (REPLACE)
    POSITION     NUMBER(6,0)   DEFAULT 100,
    ENABLED      BOOLEAN       DEFAULT TRUE,
    NOTE         VARCHAR(2000),
    UPDATED_BY   VARCHAR(256)  DEFAULT CURRENT_USER(),
    UPDATED_AT   TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DOMAIN_SKILL PRIMARY KEY (DOMAIN_ID, STAGE, SKILL_NAME)
);

CREATE SCHEMA IF NOT EXISTS {{database}}.CONFLUENCE;

CREATE TABLE IF NOT EXISTS {{database}}.CONFLUENCE.SOURCE (
    SOURCE_ID          VARCHAR(36)    NOT NULL,
    DOMAIN_ID          VARCHAR(36)    NOT NULL,
    KIND               VARCHAR(16)    NOT NULL,     -- PAGE | SPACE | UPLOAD
    CLOUD_ID           VARCHAR(64),
    SPACE_KEY          VARCHAR(255),
    PAGE_ID            VARCHAR(64),
    TITLE              VARCHAR(1024),
    URL                VARCHAR(2048),
    FILE_NAME          VARCHAR(512),
    STATUS             VARCHAR(16)    DEFAULT 'ACTIVE',   -- ACTIVE | REMOVED
    LAST_REFRESHED_AT  TIMESTAMP_LTZ,
    LAST_RESULT        VARIANT,
    CREATED_BY         VARCHAR(256)   DEFAULT CURRENT_USER(),
    CREATED_AT         TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_CONFLUENCE_SOURCE PRIMARY KEY (SOURCE_ID)
);

CREATE TABLE IF NOT EXISTS {{database}}.CONFLUENCE.PAGE (
    SOURCE_ID    VARCHAR(36)       NOT NULL,
    PAGE_ID      VARCHAR(64)       NOT NULL,
    TITLE        VARCHAR(1024),
    VERSION      NUMBER(10,0),
    TEXT_HASH    VARCHAR(64),
    TEXT         VARCHAR(16777216),
    URL          VARCHAR(2048),
    PROPOSED     NUMBER(6,0)       DEFAULT 0,
    FETCHED_AT   TIMESTAMP_LTZ     DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_CONFLUENCE_PAGE PRIMARY KEY (SOURCE_ID, PAGE_ID)
);

