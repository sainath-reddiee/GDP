-- V039 Model Workbench: one canonical, versioned model per domain, reviewed and approved in the app.
-- Applied once; never edit after it has been applied. Add a new V### instead.
--
-- GOVERNANCE.DOMAIN_MODEL         one row per domain (MODEL_ID = md5('model:' || DOMAIN_ID) as a UUID): the approved
--                                 version, the open version (at most one DRAFT or IN_REVIEW), the naming standard
--                                 drafts are checked against, the default repository and the saved diagram layout.
-- GOVERNANCE.MODEL_DESIGNS        keeps holding the versions. Canonical rows have MODEL_ID set (DESIGN_ID = MODEL_ID);
--                                 rows without one are legacy Modeling hub designs, read-only from now on.
--                                 Statuses of canonical rows: DRAFT, IN_REVIEW, APPROVED, PUBLISHED, SUPERSEDED,
--                                 REJECTED. The draft is edited in place guarded by ETAG.
-- GOVERNANCE.MODEL_REVIEW_COMMENT review threads per path (ENTITY, ENTITY.COLUMN, rel:<id>, model); unresolved
--                                 BLOCKER comments block approval.
-- GOVERNANCE.MODEL_CHANGE         a run's proposed change to the domain model (PR 3 of the workbench).
-- KNOWLEDGE.TARGET_TABLE_REGISTRY gains MODEL_ID and MODEL_VERSION: which approved version registered the table.
-- CORE.WORKFLOW_RUN gains MODEL_ID, MODEL_VERSION and MODEL_ENTITY: the approved model a run is pinned to.
--
-- The baseline (an APPROVED version 1 per active domain built from its registered targets) is written by the deploy
-- after this migration (services/modeling/domain_model.backfill), so the registry-to-specification rule exists once,
-- in Python. Every statement is safe to run again (IF NOT EXISTS).

CREATE TABLE IF NOT EXISTS {{database}}.GOVERNANCE.DOMAIN_MODEL (
    MODEL_ID              VARCHAR(36)    NOT NULL,
    DOMAIN_ID             VARCHAR(36)    NOT NULL,
    DOMAIN_NAME           VARCHAR(128)   NOT NULL,
    FORKED_FROM_MODEL_ID  VARCHAR(36),
    FORKED_FROM_VERSION   NUMBER(6,0),
    APPROVED_VERSION      NUMBER(6,0),
    OPEN_VERSION          NUMBER(6,0),
    NAMING_STANDARD       VARIANT,
    DEFAULT_REPO_ID       VARCHAR(36),
    DIAGRAM_LAYOUT        VARIANT,
    CREATED_BY            VARCHAR(256)   DEFAULT CURRENT_USER(),
    CREATED_AT            TIMESTAMP_LTZ  DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_BY            VARCHAR(256),
    UPDATED_AT            TIMESTAMP_LTZ,
    CONSTRAINT PK_DOMAIN_MODEL PRIMARY KEY (MODEL_ID),
    CONSTRAINT UQ_DOMAIN_MODEL_DOMAIN UNIQUE (DOMAIN_ID)
);

