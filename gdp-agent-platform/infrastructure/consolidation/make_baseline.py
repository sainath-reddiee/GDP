"""Generate snowflake/database/baseline/B061__platform_core.sql and prove it equals the migrations it replaces.

    python -m infrastructure.consolidation.make_baseline --connection <c> --prefix DEV_AI_PLATFORM [--check-only]

1. Builds an empty database <PREFIX>_BLA_REHEARSAL from the archived V001 to V061 (the path every existing environment
   took), then extracts its final layout: database roles and their hierarchy, the CORE, LANDING and GDP_SILVER schemas,
   every sequence, file format, stage, table (with keys, defaults, clustering, comments), row access policy and its
   attachments, view, and every grant and future grant. Names are written as {{database}}.CORE.<name>.
2. Builds <PREFIX>_BLB_REHEARSAL from that baseline alone and compares the two databases object by object (old schemas
   aside, which only the migration path leaves behind, empty). Any difference fails.
3. Runs the full deploy (seed, package, procedures, views, Cortex Search, agent) on the baseline database, proving a
   new environment provisions end to end with one command.

Only the two *_REHEARSAL databases are written. --check-only skips step 1 and checks the committed baseline.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from typing import Any, Dict, List

from infrastructure.consolidation import common
from infrastructure.consolidation.codemod import rewrite
from infrastructure.consolidation.common import LEGACY_SCHEMAS, PLATFORM_SCHEMA, ROOT, q, show, try_q
from infrastructure.consolidation.rehearse import Shared
from infrastructure.deploy_snowflake import ARCHIVE_DIR, BASELINE_COVERS, BASELINE_FILE, apply_from_session

KEEP_SCHEMAS = (PLATFORM_SCHEMA, "LANDING", "GDP_SILVER")
SKIP_TABLES = ("SCHEMA_MIGRATION", "DEPLOY_STATE")       # created by the deploy bootstrap
GRANT_ON = {"TABLE": "TABLE", "VIEW": "VIEW", "STAGE": "STAGE", "SEQUENCE": "SEQUENCE", "FILE_FORMAT": "FILE FORMAT",
            "ROW_ACCESS_POLICY": "ROW ACCESS POLICY", "SCHEMA": "SCHEMA", "DATABASE": "DATABASE"}
FUTURE_ON = {"TABLE": "TABLES", "VIEW": "VIEWS", "STAGE": "STAGES", "SEQUENCE": "SEQUENCES", "FILE_FORMAT": "FILE FORMATS",
             "PROCEDURE": "PROCEDURES", "FUNCTION": "FUNCTIONS"}


def templ(text: str, db: str) -> str:
    """Replace the build database's name by {{database}} (bare or quoted)."""
    text = text.replace(f'"{db}".', "{{database}}.")
    return re.sub(rf"(?<![A-Za-z0-9_$]){re.escape(db)}\.", "{{database}}.", text)


def gname(grant: Dict[str, Any], db: str) -> str:
    """The granted object's name with the database templated (a grant ON DATABASE names just the database)."""
    name = str(grant["name"])
    return "{{database}}" if grant["granted_on"] == "DATABASE" and name.strip('"') == db else templ(name, db)


def skipped(schema: str, name: str = "") -> bool:
    return schema not in KEEP_SCHEMAS or name in SKIP_TABLES or name.startswith("CONSOLIDATION_")


def split_name(full: str):
    parts = [p.strip('"') for p in re.findall(r'"(?:[^"]|"")+"|[^.]+', full)]
    return parts


def ddl(cur, kind: str, fqn: str) -> str:
    return q(cur, f"SELECT GET_DDL('{kind}', %s, TRUE) AS D", (fqn,))[0]["d"].strip().rstrip(";")


def stage_statements() -> List[str]:
    """CREATE STAGE statements of the archive, rewritten to CORE (GET_DDL does not cover stages)."""
    out = []
    for path in sorted(ARCHIVE_DIR.glob("*.sql")):
        sql = re.sub(r"--[^\n]*", "", path.read_text(encoding="utf-8"))
        for m in re.finditer(r"CREATE\s+STAGE\s+IF\s+NOT\s+EXISTS\s+[^;]+;", sql, re.I):
            out.append(" ".join(rewrite(m.group(0), template=False).split()))
    return out


def extract(cur, db: str) -> str:
    out: List[str] = [
        f"-- B{BASELINE_COVERS} baseline: the platform as V001 to V{BASELINE_COVERS} leave it, created directly in one schema.",
        "-- Generated by infrastructure/consolidation/make_baseline.py from a database built by those migrations, and",
        "-- checked against one (same objects, columns, keys, defaults, policies, grants). Used only for a NEW environment",
        "-- (empty ledger); the deploy then records V001 to V061 as applied. Existing environments apply",
        "-- snowflake/database/migrations/archive/ instead. Never edit: changes go into a new migration (V062 on).",
        "",
        "-- ---------------------------------------------------------------- database roles",
    ]
    roles = sorted(show(cur, "DATABASE ROLES", db), key=lambda r: r["name"])
    for r in roles:
        comment = str(r.get("comment") or "").replace("'", "''")
        out.append(f"CREATE DATABASE ROLE IF NOT EXISTS {{{{database}}}}.{r['name']} COMMENT = '{comment}';")
    grants_to: Dict[str, List[Dict[str, Any]]] = {r["name"]: q(cur, f"SHOW GRANTS TO DATABASE ROLE {db}.{r['name']}")
                                                  for r in roles}
    for role, rows_ in grants_to.items():
        for g in rows_:
            if g["granted_on"] == "DATABASE_ROLE" and g["privilege"] == "USAGE":
                out.append(f"GRANT DATABASE ROLE {templ(g['name'], db)} TO DATABASE ROLE {{{{database}}}}.{role};")

    out += ["", "-- ---------------------------------------------------------------- schemas"]
    for s in show(cur, "SCHEMAS", db):
        if s["name"] in KEEP_SCHEMAS:
            comment = str(s.get("comment") or "").replace("'", "''")
            out.append(f"CREATE SCHEMA IF NOT EXISTS {{{{database}}}}.{s['name']} COMMENT = '{comment}';")

    def objects(kind: str):
        return sorted((r for r in show(cur, kind, db) if not skipped(r["schema_name"], r["name"])),
                      key=lambda r: (r["schema_name"], r["name"]))

    out += ["", "-- ---------------------------------------------------------------- sequences"]
    for r in objects("SEQUENCES"):
        text = ddl(cur, "SEQUENCE", f"{db}.{r['schema_name']}.{r['name']}")
        out.append(templ(re.sub(r"(?i)^create or replace sequence", "CREATE SEQUENCE IF NOT EXISTS", text), db) + ";")
    out += ["", "-- ---------------------------------------------------------------- file formats"]
    for r in objects("FILE FORMATS"):
        text = ddl(cur, "FILE_FORMAT", f"{db}.{r['schema_name']}.{r['name']}")
        out.append(templ(re.sub(r"(?i)^create or replace file format", "CREATE FILE FORMAT IF NOT EXISTS", text), db) + ";")
    out += ["", "-- ---------------------------------------------------------------- stages"]
    out += stage_statements()

    tables = objects("TABLES")
    out += ["", "-- ---------------------------------------------------------------- tables (referenced tables first)"]
    texts = {}
    for r in tables:
        text = ddl(cur, "TABLE", f"{db}.{r['schema_name']}.{r['name']}")
        text = re.sub(r"(?is)\s+with row access policy\s+\S+\s+on\s+\([^)]*\)", "", text)
        text = re.sub(r"(?i)^create or replace (transient )?table", lambda m: f"CREATE {(m.group(1) or '').upper()}TABLE IF NOT EXISTS", text)
        texts[r["name"]] = templ(text, db) + ";"
    done: List[str] = []

    def place(name: str, path=()):
        if name in done or name not in texts:
            return
        for ref in re.findall(r"(?i)references\s+\{\{database\}\}\.\w+\.(\w+)", texts[name]):
            if ref.upper() != name and ref.upper() not in path:
                place(ref.upper(), (*path, name))
        done.append(name)

    for r in tables:
        place(r["name"])
    out += [texts[n] for n in done]

    out += ["", "-- ---------------------------------------------------------------- row access policies and attachments"]
    for r in objects("ROW ACCESS POLICIES"):
        fqn = f"{db}.{r['schema_name']}.{r['name']}"
        text = ddl(cur, "POLICY", fqn)
        out.append(templ(re.sub(r"(?i)^create or replace row access policy", "CREATE ROW ACCESS POLICY IF NOT EXISTS", text), db) + ";")
        for ref in q(cur, f"SELECT REF_DATABASE_NAME, REF_SCHEMA_NAME, REF_ENTITY_NAME, REF_ARG_COLUMN_NAMES FROM TABLE("
                          f"{db}.INFORMATION_SCHEMA.POLICY_REFERENCES(POLICY_NAME => %s))", (fqn,)):
            cols = ", ".join(json.loads(ref["ref_arg_column_names"])) if ref.get("ref_arg_column_names") else ""
            table = f"{{{{database}}}}.{ref['ref_schema_name']}.{ref['ref_entity_name']}"
            out.append(f"ALTER TABLE {table} DROP ALL ROW ACCESS POLICIES;")
            out.append(f"ALTER TABLE {table} ADD ROW ACCESS POLICY {{{{database}}}}.{r['schema_name']}.{r['name']} ON ({cols});")

    out += ["", "-- ---------------------------------------------------------------- views"]
    for r in objects("VIEWS"):
        out.append(templ(ddl(cur, "VIEW", f"{db}.{r['schema_name']}.{r['name']}"), db) + ";")

    out += ["", "-- ---------------------------------------------------------------- grants (every object, explicitly)"]
    lines = set()
    for role, rows_ in grants_to.items():
        for g in rows_:
            on = g["granted_on"]
            if g["privilege"] == "OWNERSHIP" or on not in GRANT_ON:
                continue
            parts = split_name(g["name"])
            if on == "SCHEMA" and parts[-1] not in KEEP_SCHEMAS:
                continue
            if on not in ("SCHEMA", "DATABASE") and skipped(parts[1], parts[-1]):
                continue
            lines.add(f"GRANT {g['privilege']} ON {GRANT_ON[on]} {gname(g, db)} TO DATABASE ROLE {{{{database}}}}.{role};")
    out += sorted(lines)
    out += ["", "-- ---------------------------------------------------------------- future grants"]
    for schema in KEEP_SCHEMAS:
        for g in try_q(cur, f"SHOW FUTURE GRANTS IN SCHEMA {db}.{schema}"):
            on = FUTURE_ON.get(g["grant_on"])
            if on and g.get("grant_to") == "DATABASE_ROLE":
                grantee = templ(g["grantee_name"], db)
                grantee = grantee if grantee.startswith("{{database}}.") else f"{{{{database}}}}.{grantee}"
                out.append(f"GRANT {g['privilege']} ON FUTURE {on} IN SCHEMA {{{{database}}}}.{schema} TO DATABASE ROLE {grantee};")
    return "\n".join(out) + "\n"


def snapshot(cur, db: str) -> Dict[str, Any]:
    """Everything that must be equal between the two paths, with the database name normalised."""
    snap: Dict[str, Any] = defaultdict(dict)
    snap["roles"] = sorted((r["name"], r.get("comment")) for r in show(cur, "DATABASE ROLES", db))
    for r in show(cur, "DATABASE ROLES", db):
        snap["grants_to_role"][r["name"]] = sorted(
            (g["privilege"], g["granted_on"], gname(g, db))
            for g in q(cur, f"SHOW GRANTS TO DATABASE ROLE {db}.{r['name']}")
            if g["privilege"] != "OWNERSHIP" and not (
                g["granted_on"] == "SCHEMA" and split_name(g["name"])[-1] not in KEEP_SCHEMAS) and not (
                g["granted_on"] not in ("SCHEMA", "DATABASE", "DATABASE_ROLE") and
                skipped(split_name(g["name"])[1], split_name(g["name"])[-1])))
    snap["schemas"] = sorted((s["name"], s.get("comment")) for s in show(cur, "SCHEMAS", db) if s["name"] in KEEP_SCHEMAS)
    for schema in KEEP_SCHEMAS:
        snap["future"][schema] = sorted((g["privilege"], g["grant_on"], templ(g["grantee_name"], db).split(".")[-1])
                                        for g in try_q(cur, f"SHOW FUTURE GRANTS IN SCHEMA {db}.{schema}"))
    cols = defaultdict(list)
    for c in q(cur, f"SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE, COLUMN_DEFAULT, "
                    f"CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, COMMENT FROM {db}.INFORMATION_SCHEMA.COLUMNS "
                    f"WHERE TABLE_SCHEMA IN ({', '.join(repr(s) for s in KEEP_SCHEMAS)}) ORDER BY 1, 2, ORDINAL_POSITION"):
        cols[(c["table_schema"], c["table_name"])].append(
            (c["column_name"], c["data_type"], c["is_nullable"], templ(str(c["column_default"]), db) if c["column_default"] else None,
             c["character_maximum_length"], c["numeric_precision"], c["numeric_scale"], c["comment"]))
    for r in show(cur, "TABLES", db):
        if skipped(r["schema_name"], r["name"]):
            continue
        fqn = f"{db}.{r['schema_name']}.{r['name']}"
        snap["tables"][f"{r['schema_name']}.{r['name']}"] = {
            "columns": cols[(r["schema_name"], r["name"])],
            "props": [r.get(k) for k in ("kind", "cluster_by", "change_tracking", "comment")],
            "pk": sorted(x["column_name"] for x in try_q(cur, f"SHOW PRIMARY KEYS IN TABLE {fqn}")),
            "fk": sorted(f"{x['fk_column_name']}->{x['pk_table_name']}.{x['pk_column_name']}"
                         for x in try_q(cur, f"SHOW IMPORTED KEYS IN TABLE {fqn}")),
            "policies": sorted(x["policy_name"] for x in try_q(
                cur, f"SELECT POLICY_NAME FROM TABLE({db}.INFORMATION_SCHEMA.POLICY_REFERENCES("
                     f"REF_ENTITY_NAME => %s, REF_ENTITY_DOMAIN => 'table'))", (fqn,))),
        }
    for kind, key in (("VIEWS", "text"), ("SEQUENCES", "interval"), ("FILE FORMATS", "format_options"),
                      ("STAGES", "directory_enabled"), ("ROW ACCESS POLICIES", "comment")):
        for r in show(cur, kind, db):
            if not skipped(r["schema_name"], r["name"]):
                value = templ(str(r.get(key)), db) if key == "text" else r.get(key)
                snap[kind][f"{r['schema_name']}.{r['name']}"] = [value, r.get("comment")]
    for r in show(cur, "STAGES", db):
        if not skipped(r["schema_name"], r["name"]):
            desc = {d["property"]: d["property_value"] for d in try_q(cur, f"DESCRIBE STAGE {db}.{r['schema_name']}.{r['name']}")
                    if d.get("property") in ("FORMAT_NAME", "TYPE", "ENABLE")}
            snap["stage_props"][f"{r['schema_name']}.{r['name']}"] = {k: templ(str(v), db) for k, v in desc.items()}
    for r in show(cur, "ROW ACCESS POLICIES", db):
        if not skipped(r["schema_name"], r["name"]):
            body = try_q(cur, f"DESCRIBE ROW ACCESS POLICY {db}.{r['schema_name']}.{r['name']}")
            snap["policy_body"][r["name"]] = " ".join(templ(str(body[0].get("body")), db).split()) if body else None
    return json.loads(json.dumps(snap, default=str))


def diff(a: Any, b: Any, path: str = "") -> List[str]:
    if isinstance(a, dict) and isinstance(b, dict):
        out = []
        for k in sorted(set(a) | set(b)):
            if k not in a:
                out.append(f"{path}/{k}: only in the baseline database")
            elif k not in b:
                out.append(f"{path}/{k}: only in the migration database")
            else:
                out += diff(a[k], b[k], f"{path}/{k}")
        return out
    return [] if a == b else [f"{path}: migrations {str(a)[:300]} | baseline {str(b)[:300]}"]


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--connection", required=True)
    p.add_argument("--prefix", required=True, help="name prefix of the two scratch databases")
    p.add_argument("--warehouse", default="DBT_WH")
    p.add_argument("--role")
    p.add_argument("--check-only", action="store_true")
    p.add_argument("--skip-full-deploy", action="store_true")
    p.add_argument("--replace", action="store_true", help="drop the two scratch databases first if they exist")
    args = p.parse_args()
    prefix = args.prefix.upper()
    a, b = f"{prefix}_BLA_REHEARSAL", f"{prefix}_BLB_REHEARSAL"
    con = common.connect(argparse.Namespace(connection=args.connection, role=args.role, warehouse=args.warehouse))
    shared, cur = Shared(con), con.cursor()
    cur.execute(f"USE WAREHOUSE {args.warehouse}")

    def build(db: str, use_baseline: bool) -> None:
        assert db.endswith("_REHEARSAL")
        if args.replace and q(cur, f"SHOW DATABASES LIKE '{db}'"):
            cur.execute(f"DROP DATABASE {db}")   # one of this script's own scratch databases
        assert not q(cur, f"SHOW DATABASES LIKE '{db}'"), f"{db} already exists: pass --replace"
        for line in apply_from_session(shared, db, args.warehouse, rehearsal=True, through=BASELINE_COVERS,
                                       use_baseline=use_baseline):
            print(f"  {line}")

    print(f"===== {a}: archived migrations V001 to V{BASELINE_COVERS}", flush=True)
    build(a, use_baseline=False)
    if not args.check_only:
        BASELINE_FILE.parent.mkdir(parents=True, exist_ok=True)
        BASELINE_FILE.write_text(extract(cur, a), encoding="utf-8", newline="\n")
        print(f"wrote {BASELINE_FILE.relative_to(ROOT)}", flush=True)
    print(f"===== {b}: baseline", flush=True)
    build(b, use_baseline=True)
    print("===== compare", flush=True)
    problems = diff(snapshot(cur, a), snapshot(cur, b))
    leftovers = sorted(s["name"] for s in show(cur, "SCHEMAS", b) if s["name"] in LEGACY_SCHEMAS)
    if leftovers:
        problems.append(f"the baseline database has old schemas: {leftovers}")
    for line in problems:
        print(f"  DIFF {line}")
    print(f"equivalence: {'IDENTICAL' if not problems else f'{len(problems)} difference(s)'}", flush=True)
    if not problems and not args.skip_full_deploy:
        print(f"===== {b}: full deploy of a new environment", flush=True)
        for line in apply_from_session(shared, b, args.warehouse, rehearsal=True):
            print(f"  {line}")
        procs = [r for r in show(cur, "PROCEDURES", b) if r["schema_name"] == PLATFORM_SCHEMA]
        print(f"new environment: {len(procs)} procedures in {PLATFORM_SCHEMA}; schemas "
              f"{sorted(s['name'] for s in show(cur, 'SCHEMAS', b))}")
    con.close()
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
