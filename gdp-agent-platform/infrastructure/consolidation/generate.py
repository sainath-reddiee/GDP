"""Generate V061 (the renames into CORE) and the compatibility views from services.common.platform_schema.MOVED.

    python -m infrastructure.consolidation.generate          # write both files
    python -m infrastructure.consolidation.generate --check  # fail if the committed files differ (used by tests)

V061 is generated once and committed; after it has been applied anywhere it is never regenerated (the migration
checksum would change). tests/unit/test_platform_schema.py checks that the committed file still matches MOVED.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from services.common.platform_schema import PLATFORM_SCHEMA, RENAME, moved  # noqa: E402

V061 = ROOT / "snowflake" / "database" / "migrations" / "V061__consolidate_platform_schema.sql"
COMPAT = ROOT / "snowflake" / "views" / "compat_legacy.sql"

# Credential and sign-in rows: never readable through a second name, not even for a transition.
NO_COMPAT_VIEW = {("JIRA", "USER_TOKEN"), ("JIRA", "OAUTH_STATE")}

# Roles that had USAGE on any schema that moves (V002 to V059). USAGE alone grants no table access; object grants
# moved with each object.
USAGE_ROLES = ("VIEWER", "DATA_ENGINEER", "REVIEWER", "QA_ENGINEER", "OPS_VIEWER", "OPS_SERVICE")

# Column defaults that name a sequence by its full name. Re-pointed after the sequences move (Snowflake allows SET
# DEFAULT only from one sequence to another, which is this case).
SEQUENCE_DEFAULTS = (
    ("CASE_RECORD", "CASE_NUMBER", "CASE_SEQ"),
    ("INGESTION_CONTROL_CONFIG", "MASTER_ID", "SEQ_INGESTION_MASTER_ID"),
    ("INGESTION_CONTROL_CONFIG", "CHILD_ID", "SEQ_INGESTION_CHILD_ID"),
)

ORDER = ("SEQUENCE", "FILE FORMAT", "STAGE", "ROW ACCESS POLICY", "TABLE", "VIEW")


def v061_sql() -> str:
    s = PLATFORM_SCHEMA
    out = [
        "-- V061 consolidate the platform schemas into CORE (zero data loss).",
        "-- Generated by infrastructure/consolidation/generate.py from services/common/platform_schema.py (MOVED).",
        "-- Every statement moves an object in place with ALTER ... RENAME TO: the same object keeps its rows, staged",
        "-- files, Time Travel history, constraints and grants. Nothing is dropped, replaced or rewritten. IF EXISTS makes",
        "-- a re-run after a partial failure skip what already moved; a rename never overwrites an existing name.",
        "-- Procedures, reporting views, Cortex Search services and the agent are recreated in CORE by the same deploy;",
        "-- tasks, git repositories and the network rule by infrastructure/consolidation/runtime.py. Secrets stay where",
        "-- they are (Snowflake has no ALTER SECRET ... RENAME). LANDING and GDP_SILVER (client data) do not move.",
        "-- The deploy applies this migration only with --consolidate after a completed baseline, unless the platform",
        "-- schemas hold no rows at all (a fresh environment).",
        "-- Applied once; never edit after it has been applied to an environment - add a new V### instead.",
        "",
        "-- ---------------------------------------------------------------- schema usage for roles of the old schemas",
    ]
    for role in USAGE_ROLES:
        out.append(f"GRANT USAGE ON SCHEMA {{{{database}}}}.{s} TO DATABASE ROLE {{{{database}}}}.{role};")
    rows = moved(method=RENAME)
    for kind in ORDER:
        group = [r for r in rows if r[2] == kind]
        if not group:
            continue
        out += ["", f"-- ---------------------------------------------------------------- {kind.lower()}s"]
        for old_schema, old_name, _, new_name, _ in group:
            out.append(f"ALTER {kind} IF EXISTS {{{{database}}}}.{old_schema}.{old_name} "
                       f"RENAME TO {{{{database}}}}.{s}.{new_name};")
    out += [
        "",
        "-- ---------------------------------------------------------------- references by full name",
        "-- Column defaults that name a sequence",
    ]
    for table, column, seq in SEQUENCE_DEFAULTS:
        out.append(f"ALTER TABLE {{{{database}}}}.{s}.{table} ALTER COLUMN {column} "
                   f"SET DEFAULT {{{{database}}}}.{s}.{seq}.NEXTVAL;")
    out += [
        "-- The staged-share landing stage names its file format",
        f"ALTER STAGE {{{{database}}}}.{s}.LANDING_STAGE SET FILE_FORMAT = "
        f"(FORMAT_NAME = '{{{{database}}}}.{s}.PARQUET_SNAPPY');",
        "-- The case visibility policy reads the domain tables by full name (same rule as V034)",
        f"ALTER ROW ACCESS POLICY {{{{database}}}}.{s}.DOMAIN_SCOPE SET BODY ->",
        "    ROW_DOMAIN IS NULL",
        "    OR IS_DATABASE_ROLE_IN_SESSION('PLATFORM_ADMIN')",
        f"    OR ROW_DOMAIN IN (SELECT DOMAIN_ID FROM {{{{database}}}}.{s}.DOMAIN_REGISTRY "
        "WHERE UPPER(DOMAIN_NAME) = 'GENERAL')",
        f"    OR ROW_DOMAIN IN (SELECT DOMAIN_ID FROM {{{{database}}}}.{s}.DOMAIN_MEMBER "
        "WHERE UPPER(USER_NAME) = UPPER(CURRENT_USER()))",
        f"    OR ROW_DOMAIN NOT IN (SELECT DOMAIN_ID FROM {{{{database}}}}.{s}.DOMAIN_MEMBER);",
        "-- The profile alias view selects from its base table by full name",
        f"CREATE OR REPLACE VIEW {{{{database}}}}.{s}.PERSISTENT_PROFILES COPY GRANTS",
        "  COMMENT = 'Alias of CORE.DATA_PROFILES'",
        f"AS SELECT * FROM {{{{database}}}}.{s}.DATA_PROFILES;",
        "",
        "-- ---------------------------------------------------------------- future grants",
        "-- One schema now holds credential and PII tables as well, so new objects are no longer readable by default:",
        "-- every later migration grants each object it creates (tests/unit/test_platform_schema.py enforces it).",
        "-- Revoking a future grant leaves every grant already made in place.",
        f"REVOKE SELECT ON FUTURE TABLES IN SCHEMA {{{{database}}}}.{s} FROM DATABASE ROLE {{{{database}}}}.VIEWER;",
        "",
    ]
    return "\n".join(out)


def compat_sql() -> str:
    s = PLATFORM_SCHEMA
    out = [
        "-- Read-only compatibility views: the names used before V061, over the objects that moved into CORE.",
        "-- Generated by infrastructure/consolidation/generate.py. Transition only (30 days after cut-over); removed at",
        "-- cleanup. They are created without grants: infrastructure/consolidation/runtime.py grants on each view exactly",
        "-- the SELECT grants its base table had before the move (COPY GRANTS keeps them on every re-apply). No view for",
        "-- credential tables. SELECT * is safe here because this file is re-applied after every migration, which is",
        "-- when columns change. Row access policies on the base tables apply through the views. Views cannot be",
        "-- written to, so application code uses CORE only.",
        "",
    ]
    for old_schema, old_name, kind, new_name, _ in moved(method=RENAME, types=("TABLE", "VIEW")):
        if (old_schema, old_name) in NO_COMPAT_VIEW:
            continue
        out.append(f"CREATE OR REPLACE VIEW {{{{database}}}}.{old_schema}.{old_name} COPY GRANTS "
                   f"COMMENT = 'Compatibility view (read-only) of {s}.{new_name}; use {s}.{new_name}' "
                   f"AS SELECT * FROM {{{{database}}}}.{{{{schema}}}}.{new_name};")
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    targets = [(V061, v061_sql()), (COMPAT, compat_sql())]
    if args.check:
        stale = [p.name for p, text in targets if not p.exists() or p.read_text(encoding="utf-8") != text]
        assert not stale, f"regenerate: {stale}"
        return
    for path, text in targets:
        if path == V061 and path.exists() and path.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{path.name} exists and differs; it may already be applied. Not overwritten.")
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
