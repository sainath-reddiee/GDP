import { chromium } from "@playwright/test";
const out = process.argv[2], BASE = "http://localhost:3000";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 } });
await ctx.addCookies([{ name: "aip_dev", value: "1", url: BASE }]);
await ctx.addInitScript(() => { try { localStorage.setItem("aip.theme", "light"); } catch {} });
const p = await ctx.newPage(); const errs = []; p.on("pageerror", (e) => errs.push(String(e).slice(0, 150)));
await p.goto(BASE + "/dashboard/onboarding", { waitUntil: "domcontentloaded", timeout: 180000 }); await p.waitForTimeout(8000);
await p.getByTestId("onboard-source").hover(); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/1-start-hover.png`, clip: { x: 0, y: 0, width: 1600, height: 560 } });
const visible = async () => ({ src: await p.getByTestId("onboard-source").count(), dom: await p.getByTestId("onboard-domain").count(), app: await p.getByTestId("onboard-application").count() });
const s1 = await visible();
await p.getByTestId("onboard-source").click(); await p.waitForURL(/type=source/); await p.waitForTimeout(6000);
const s2 = await visible();
await p.screenshot({ path: `${out}/2-source.png`, clip: { x: 0, y: 0, width: 1600, height: 560 } });
await p.getByTestId("onboard-source-share").click(); await p.waitForTimeout(2500);
const s3 = { share: await p.getByTestId("onboard-source-share").count(), external: await p.getByTestId("onboard-source-external").count() };
await p.screenshot({ path: `${out}/3-share.png`, clip: { x: 0, y: 0, width: 1600, height: 760 } });
await p.getByTestId("onboard-source-change").click(); await p.waitForTimeout(500);
const s4 = { share: await p.getByTestId("onboard-source-share").count(), external: await p.getByTestId("onboard-source-external").count() };
console.log(JSON.stringify({ start: s1, afterSource: s2, afterShare: s3, afterChange: s4, errs }));
await b.close();
